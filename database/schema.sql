-- Run this script in Oracle SQL Developer to initialize the SOC Threat Ledger
CREATE TABLE Threat_Logs (
    alert_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    source_ip VARCHAR2(45) NOT NULL,
    destination_ip VARCHAR2(45) NOT NULL,
    confidence_score NUMBER(5, 4) NOT NULL,
    threat_severity VARCHAR2(20) DEFAULT 'Harmful',
    anomaly_origin VARCHAR2(30) DEFAULT 'Known Dataset'
);
CREATE TABLE Generated_Rules (
    rule_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id NUMBER REFERENCES Threat_Logs(alert_id) ON DELETE CASCADE,
    snort_syntax VARCHAR2(255)
);